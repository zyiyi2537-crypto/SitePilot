import crypto from "node:crypto";

import { PolicyError } from "./core.js";

function planHash(plan) {
  return crypto.createHash("sha256").update(JSON.stringify(plan.routes)).digest("hex");
}

function componentName(page) {
  const value = String(page).split(/[^A-Za-z0-9]+/).filter(Boolean).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
  return /^[A-Za-z]/.test(value) ? value : `Page${value}`;
}

function pageSource(route, plan) {
  const components = route.components.map((component) => {
    const source = `${component.source.repository}:${component.source.path}@${component.source.commit}`;
    const marker = `data-component="${component.name}" data-source="${source}"`;
    const blocks = {
      Hero: `<section ${marker} aria-labelledby="sitepilot-hero-title"><p data-eyebrow="true">SitePilot draft</p><h1 id="sitepilot-hero-title">A clear starting point for your website</h1><p data-copy="hero">Content will be replaced with approved customer facts.</p><a href="#contact">Talk to our team</a></section>`,
      ProductGrid: `<section ${marker} aria-labelledby="sitepilot-products-title"><h2 id="sitepilot-products-title">Products</h2><div data-grid="products"><article><h3>Product overview</h3><p>Approved product information will appear here.</p></article></div></section>`,
      TechnicalProof: `<section ${marker} aria-labelledby="sitepilot-proof-title"><h2 id="sitepilot-proof-title">Technical proof</h2><ul><li data-proof="pending">Evidence-backed specifications pending review</li></ul></section>`,
      ContactForm: `<section ${marker} id="contact" aria-labelledby="sitepilot-contact-title"><h2 id="sitepilot-contact-title">Contact</h2><form><label htmlFor="sitepilot-email">Email</label><input id="sitepilot-email" name="email" type="email" required autoComplete="email" /><button type="submit">Send inquiry</button></form></section>`,
      FAQ: `<section ${marker} aria-labelledby="sitepilot-faq-title"><h2 id="sitepilot-faq-title">FAQ</h2><details><summary>Frequently asked question</summary><p>Answer requires approved customer content.</p></details></section>`,
      CTA: `<section ${marker} aria-labelledby="sitepilot-cta-title"><h2 id="sitepilot-cta-title">Ready to continue?</h2><a href="#contact">Contact us</a></section>`,
    };
    return blocks[component.name] || `<section ${marker} aria-labelledby="sitepilot-${component.name}-title"><h2 id="sitepilot-${component.name}-title">${component.name}</h2><p data-content-status="pending">Approved content is required.</p></section>`;
  }).join("\n");
  return `// Generated by SitePilot from ${plan.planVersion}; source manifest: ${plan.sourceManifestHash}\nexport default function ${componentName(route.page)}Page() {\n  return (\n    <main data-sitepilot-page="${route.page}">\n${components}\n    </main>\n  );\n}\n`;
}

export async function materializePagePlan({ plan, worktree, grant, expectedSourceManifestHash, sourceResolver } = {}) {
  if (!plan || !Array.isArray(plan.routes)) throw new PolicyError("A page plan is required", "INVALID_INPUT");
  if (!worktree || typeof worktree.applyPatch !== "function") throw new PolicyError("A worktree policy is required", "CONFIG_REQUIRED");
  if (grant?.level !== "L2") throw new PolicyError("Writing generated code requires an L2 grant", "POLICY_DENIED");
  if (plan.writesAllowed !== false) throw new PolicyError("Only reviewed page plans can be materialized", "POLICY_DENIED");
  if (expectedSourceManifestHash && expectedSourceManifestHash !== plan.sourceManifestHash) {
    throw new PolicyError("Page plan source manifest is stale", "STALE_REVISION");
  }
  if (planHash(plan) !== plan.sourceManifestHash) throw new PolicyError("Page plan source manifest is invalid", "STALE_REVISION");
  const files = Object.fromEntries(plan.routes.map((route) => [route.file, pageSource(route, plan)]));
  const sources = [];
  if (sourceResolver !== undefined && typeof sourceResolver !== "function") throw new PolicyError("Source resolver must be a function", "CONFIG_REQUIRED");
  if (sourceResolver) {
    const unique = new Map(plan.routes.flatMap((route) => route.components).map((component) => [JSON.stringify(component.source), component.source]));
    for (const source of unique.values()) {
      const fetched = await sourceResolver(source);
      if (!fetched || fetched.repository !== source.repository || fetched.commit !== source.commit || fetched.path !== source.path || typeof fetched.content !== "string") {
        throw new PolicyError("Resolved component source does not match the frozen plan", "STALE_REVISION");
      }
      const safeName = `${source.repository}-${source.path}`.replace(/[^A-Za-z0-9_.-]+/g, "_");
      const file = `src/generated/sources/${safeName}`;
      files[file] = fetched.content;
      sources.push({ ...source, file });
    }
  }
  files["src/generated/sitepilot-manifest.json"] = `${JSON.stringify({
    planVersion: plan.planVersion,
    projectId: plan.projectId,
    runId: plan.runId,
    sourceManifestHash: plan.sourceManifestHash,
    routes: plan.routes,
    sources,
  }, null, 2)}\n`;
  files["SOURCES.md"] = `${sources.length ? sources.map((source) => `- ${source.repository} ${source.commit} ${source.path} (CodeAtlas evidence; review required)`).join("\n") : "- No external component source was materialized."}\n`;
  const result = await worktree.applyPatch(files);
  return Object.freeze({
    files: result.files,
    sourceManifestHash: plan.sourceManifestHash,
    generated: true,
  });
}
