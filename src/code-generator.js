import crypto from "node:crypto";

import { PolicyError } from "./core.js";

function planHash(plan) {
  return crypto.createHash("sha256").update(JSON.stringify(plan.routes)).digest("hex");
}

function pageSource(route, plan) {
  const components = route.components.map((component) => `      <section data-component="${component.name}" data-source="${component.source.repository}:${component.source.path}@${component.source.commit}">${component.name}</section>`).join("\n");
  return `// Generated by SitePilot from ${plan.planVersion}; source manifest: ${plan.sourceManifestHash}\nexport default function ${route.page[0].toUpperCase()}${route.page.slice(1)}Page() {\n  return (\n    <main data-sitepilot-page="${route.page}">\n${components}\n    </main>\n  );\n}\n`;
}

export async function materializePagePlan({ plan, worktree, grant, expectedSourceManifestHash, sourceResolver } = {}) {
  if (!plan || !Array.isArray(plan.routes)) throw new PolicyError("A page plan is required", "INVALID_INPUT");
  if (!worktree || typeof worktree.applyPatch !== "function") throw new PolicyError("A worktree policy is required", "CONFIG_REQUIRED");
  if (grant?.level !== "L2") throw new PolicyError("Writing generated code requires an L2 grant", "POLICY_DENIED");
  if (plan.writesAllowed !== false) throw new PolicyError("Only reviewed page plans can be materialized", "POLICY_DENIED");
  if (expectedSourceManifestHash && expectedSourceManifestHash !== plan.sourceManifestHash) {
    throw new PolicyError("Page plan source manifest is stale", "STALE_REVISION");
  }
  if (planHash(plan) !== plan.sourceManifestHash) throw new PolicyError("Page plan source manifest is invalid", "STALE_REVISION");
  const files = Object.fromEntries(plan.routes.map((route) => [route.file, pageSource(route, plan)]));
  const sources = [];
  if (sourceResolver !== undefined && typeof sourceResolver !== "function") throw new PolicyError("Source resolver must be a function", "CONFIG_REQUIRED");
  if (sourceResolver) {
    const unique = new Map(plan.routes.flatMap((route) => route.components).map((component) => [JSON.stringify(component.source), component.source]));
    for (const source of unique.values()) {
      const fetched = await sourceResolver(source);
      if (!fetched || fetched.repository !== source.repository || fetched.commit !== source.commit || fetched.path !== source.path || typeof fetched.content !== "string") {
        throw new PolicyError("Resolved component source does not match the frozen plan", "STALE_REVISION");
      }
      const safeName = `${source.repository}-${source.path}`.replace(/[^A-Za-z0-9_.-]+/g, "_");
      const file = `src/generated/sources/${safeName}`;
      files[file] = fetched.content;
      sources.push({ ...source, file });
    }
  }
  files["src/generated/sitepilot-manifest.json"] = `${JSON.stringify({
    planVersion: plan.planVersion,
    projectId: plan.projectId,
    runId: plan.runId,
    sourceManifestHash: plan.sourceManifestHash,
    routes: plan.routes,
    sources,
  }, null, 2)}\n`;
  const result = await worktree.applyPatch(files);
  return Object.freeze({
    files: result.files,
    sourceManifestHash: plan.sourceManifestHash,
    generated: true,
  });
}
