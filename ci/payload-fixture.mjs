import fs from 'node:fs/promises';
import crypto from 'node:crypto';
import { createPayloadDraftPlan } from '../src/payload-template.js';
import lock from '../sources/payload-website.lock.json' with { type: 'json' };

// Synthetic acceptance data, never customer claims or an approved delivery.
const page = 'sitepilot-ci';
const route = '/sitepilot-ci';
const components = [
  { instanceId: 'hero_ci_1', registryId: 'payload-hero', name: 'Hero', props: { variant: 'lowImpact' }, source: { repository: lock.repositoryId, commit: lock.commit, path: 'templates/website/src/heros/LowImpact/index.tsx' } },
  { instanceId: 'content_ci_1', registryId: 'payload-content', name: 'Content', props: { columns: 1 }, source: { repository: lock.repositoryId, commit: lock.commit, path: 'templates/website/src/blocks/Content/config.ts' } },
  { instanceId: 'cta_ci_1', registryId: 'payload-cta', name: 'CTA', props: { links: 0 }, source: { repository: lock.repositoryId, commit: lock.commit, path: 'templates/website/src/blocks/CallToAction/config.ts' } },
];
const designDraftId = 'design_ci_synthetic';
const designHash = crypto.createHash('sha256').update(JSON.stringify({ page, route, components })).digest('hex');
const designDraft = {
  id: designDraftId,
  designHash,
  pageTree: [{ page, route, components }],
};
const pagePlan = {
  routes: [{
    page,
    route,
    components: components.map(({ instanceId, props, ...component }) => component),
  }],
};
const plan = createPayloadDraftPlan({
  projectId: 'ci-synthetic-website',
  strategy: { pageHierarchy: [page], blocks: ['Hero', 'Content', 'CTA'] },
  locales: ['en'],
  designDraft,
  pagePlan,
  contentByPage: {
    [page]: {
      title: 'SitePilot synthetic acceptance website',
      heroTitle: 'SitePilot CMS draft preview',
      description: 'Synthetic content generated by the SitePilot draft planner for CI acceptance only.',
      cta: 'Review this synthetic website draft',
      claimRefs: ['ci-synthetic-content-v1'],
    },
  },
});
const httpPage = 'sitepilot-http-ci';
const httpRoute = '/' + httpPage;
const httpComponents = components.map((component) => ({ ...component, instanceId: component.instanceId + '_http' }));
const httpDesignHash = crypto.createHash('sha256').update(JSON.stringify({ page: httpPage, route: httpRoute, components: httpComponents, parent: designHash })).digest('hex');
const httpPlan = createPayloadDraftPlan({
  projectId: 'ci-synthetic-website',
  strategy: { pageHierarchy: [httpPage], blocks: ['Hero', 'Content', 'CTA'] },
  locales: ['en'],
  designDraft: { id: 'design_ci_http', designHash: httpDesignHash, pageTree: [{ page: httpPage, route: httpRoute, components: httpComponents }] },
  pagePlan: { routes: [{ page: httpPage, route: httpRoute, components: httpComponents.map(({ instanceId, props, ...component }) => component) }] },
  contentByPage: {
    [httpPage]: {
      title: 'SitePilot HTTP adapter draft',
      heroTitle: 'SitePilot CMS draft preview',
      description: 'Synthetic content generated by the SitePilot draft planner for CI acceptance only.',
      cta: 'Review this synthetic website draft',
      claimRefs: ['ci-synthetic-content-v1'],
    },
  },
});
await fs.mkdir('ci-results', { recursive: true });
await fs.writeFile('ci-results/draft-plan.json', JSON.stringify({ ...plan, httpDraft: httpPlan, synthetic: true, sourceCommit: lock.commit }, null, 2));
console.log('Generated synthetic DesignDraft mappings for Local API and HTTP adapter acceptance.');
